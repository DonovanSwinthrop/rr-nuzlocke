/* RR Nuzlocke Web - offline service worker.
   Keeps every app file on the phone so the app opens and plays with no internet (after one online visit).
   It also adds the two security headers the emulator's threads need, so isolation works offline and on hosts that
   can't set headers (GitHub Pages). Generated by prepare.js: VERSION and FILES are filled in from the app folder. */
const VERSION = "9e2ca017055c";
const FILES = ["./","./app.css","./app.js","./icon-192.png","./icon-512.png","./index.html","./manifest.webmanifest","./memstate.js","./mgba/mgba.js","./mgba/mgba.wasm","./overlay/builder.js","./overlay/core.js","./overlay/data.js","./overlay/dex.js","./overlay/engine.js","./overlay/items.js","./overlay/linebuild.js","./overlay/lines.js","./overlay/manifest.webmanifest","./overlay/overlay.css","./overlay/overlay.html","./overlay/overlay.js","./overlay/overlaydata.js","./overlay/planner-worker.js","./overlay/rr-web.js","./overlay/rrmoves.js","./overlay/savedata.js","./overlay/savereader.js","./overlay/sprites.js","./overlay/themes.js","./overlay/where.js","./version.js"];
const CACHE = 'rrweb-' + VERSION;

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(f => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('rrweb-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('message', e => { if (e.data === 'skipWaiting') self.skipWaiting(); });

// Same response, plus the cross-origin isolation headers.
function isolate(res) {
  if (!res || res.status === 0 || res.type === 'opaque') return res;
  const h = new Headers(res.headers);
  h.set('Cross-Origin-Opener-Policy', 'same-origin');
  h.set('Cross-Origin-Embedder-Policy', 'require-corp');
  h.set('Cross-Origin-Resource-Policy', 'same-origin');
  return new Response(res.body, { status: res.status, statusText: res.statusText, headers: h });
}

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (new URL(req.url).pathname.startsWith('/api/')) return; // cloud saves always go to the network, never the cache
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // the app page itself: "/" and "/index.html" are the same file
    const key = req.mode === 'navigate' && new URL(req.url).pathname.endsWith('/') ? new URL('index.html', req.url).href : req;
    const hit = await cache.match(key, { ignoreSearch: true });
    if (hit) return isolate(hit); // offline-first: the copy on the phone
    try {
      const res = await fetch(req);
      if (res.ok && res.type === 'basic') cache.put(key, res.clone());
      return isolate(res);
    } catch (err) {
      return new Response('Offline and this file is not saved yet. Open the app once with internet.', { status: 503, headers: { 'Content-Type': 'text/plain' } });
    }
  })());
});
